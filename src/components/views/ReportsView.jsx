import React, { useState } from 'react';
import { 
  FileText, 
  Download, 
  RefreshCw, 
  Copy, 
  Check,
  FileCheck
} from 'lucide-react';
import { INCIDENT_DATA, VESSELS } from '../../data/mockData';

export default function ReportsView() {
  const [isGenerating, setIsGenerating] = useState(false);
  const [reportText, setReportText] = useState(null);
  const [copied, setCopied] = useState(false);

  const topVessel = VESSELS[0]; // MV Solara

  const generateReport = () => {
    setIsGenerating(true);
    setTimeout(() => {
      const generated = `================================================================================
NEERAKSH / TIDEMARK — MARITIME INCIDENT EVIDENCE REPORT
OFFICIAL ENVIRONMENTAL VIOLATION REPORT // MARPOL ANNEX I
================================================================================
REPORT ID:            ${INCIDENT_DATA.id}
DATE & TIMESTAMP:     2026-09-06 08:30 UTC
GENERATED BY:         Neeraksh Maritime Intelligence Platform v2.4
GEO-REGION:           ${INCIDENT_DATA.region}

--------------------------------------------------------------------------------
1. INCIDENT & SATELLITE DETECTION METRICS
--------------------------------------------------------------------------------
Spill Location:       ${INCIDENT_DATA.location}
Coordinates:          Lat 61.42° N, Long 004.18° E
Detection Timestamp:  ${INCIDENT_DATA.detectionTime}
Estimated Leak Onset: ${INCIDENT_DATA.estimatedOnset}
Initial Slick Area:   14.8 sq km (Expands to 28.4 sq km under drift model)
Confidence Level:     ${INCIDENT_DATA.confidence} (Mineral Crude Oil Confirmed)
SAR Satellite Pass:   Sentinel-1A C-band SAR (Pass ID: ${INCIDENT_DATA.sarPassId})
Wind & Drift Vectors: ${INCIDENT_DATA.windVector} | Drift: ${INCIDENT_DATA.currentDrift}

--------------------------------------------------------------------------------
2. PRIMARY ATTRIBUTED RESPONSIBLE VESSEL
--------------------------------------------------------------------------------
Vessel Name:          ${topVessel.name}
Vessel Type:          ${topVessel.type}
Flag State:           ${topVessel.flag}
MMSI Number:          ${topVessel.mmsi}
IMO Number:           ${topVessel.imo}
Callsign:             ${topVessel.callsign}

ATTRIBUTION SCORE:    91 / 100 (HIGH CONFIDENCE CANDIDATE MATCH)
Confidence Category:  HIGH
Cross-Checked Status: CONFIRMED VIA SAR HULL RADAR REFLECTION

--------------------------------------------------------------------------------
3. FORENSIC EVIDENCE & ANOMALY LOG
--------------------------------------------------------------------------------
[EVIDENCE #1] TRANSPONDER GAP DETECTED:
  - AIS transponder dark from T-2.0h to T+0.0h (05:42 UTC to 07:42 UTC).
  - Transponder turned off precisely at calculated leak origin coordinates.

[EVIDENCE #2] SPEED & ACCELERATION ANOMALY:
  - Vessel speed recorded at 11.0 kts prior to transponder gap.
  - Upon signal resumption at 07:45 UTC, speed spiked to 17.4 kts (+6.2 kt anomaly).

[EVIDENCE #3] SPATIO-TEMPORAL TRAJECTORY CORRELATION:
  - Back-drifting oil slick polygon intersects MV Solara historical position at 05:42 UTC.
  - SAR radar backscatter shows continuous dark wake trailing along vessel track.

--------------------------------------------------------------------------------
4. OTHER TRAFFIC IN AREA (SECONDARY CANDIDATES)
--------------------------------------------------------------------------------
1. Helios Star (Product Tanker) | MMSI 248301772 | Score: 34/100 (Low)
2. Nordic Carrier (Bulk Carrier) | MMSI 219004521 | Score: 18/100 (Cleared)
3. Pacific Voyager (Container Ship) | MMSI 371029384 | Score: 12/100 (Cleared)
4. Coastal Guard 14 (Patrol) | MMSI 259811004 | Official Response Intercept

--------------------------------------------------------------------------------
5. RECOMMENDED LEGAL & ENFORCEMENT ACTION
--------------------------------------------------------------------------------
[ACTION 1] Dispatch Patrol Vessel Coastal Guard 14 to intercept MV Solara at 61.60°N, 4.40°E.
[ACTION 2] Perform physical oil sampling from bilge/cargo tanks for chemical fingerprinting.
[ACTION 3] Issue formal notice to Panama Maritime Authority regarding MARPOL Annex I violation.
[ACTION 4] Preserve Sentinel-1 raw SAR geotiff and AIS transponder gap telemetry for legal prosecution.

================================================================================
END OF REPORT // ENCRYPTED HASH DIGEST: 0x9f8b4a2e1d7c3b...
================================================================================`;

      setReportText(generated);
      setIsGenerating(false);
    }, 450);
  };

  const handleDownload = () => {
    if (!reportText) return;
    const blob = new Blob([reportText], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `NEERAKSH_Incident_Report_${INCIDENT_DATA.id}.txt`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  const handleCopy = () => {
    if (!reportText) return;
    navigator.clipboard.writeText(reportText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="space-y-6">
      
      {/* Header */}
      <div className="bg-[#0f172a] p-5 sm:p-6 rounded-2xl border border-slate-800 shadow-sm flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <div className="flex items-center gap-2 mb-1.5">
            <FileText className="w-4 h-4 text-sky-400" />
            <span className="text-xs font-semibold text-sky-400 uppercase tracking-wide">
              Official Evidence Dossier
            </span>
          </div>
          <h2 className="text-xl sm:text-2xl font-bold text-white tracking-tight">
            Incident Investigation Report
          </h2>
          <p className="text-xs sm:text-sm text-slate-300 mt-1">
            Compile findings and telemetry into a formalized summary report for maritime authorities.
          </p>
        </div>

        {/* Action Buttons */}
        <div className="flex flex-wrap items-center gap-2.5">
          <button
            type="button"
            onClick={generateReport}
            disabled={isGenerating}
            className="px-4 py-2 rounded-xl bg-sky-600 hover:bg-sky-500 text-white text-xs font-medium transition-colors shadow-xs flex items-center gap-2 disabled:opacity-50 cursor-pointer"
          >
            {isGenerating ? (
              <>
                <RefreshCw className="w-4 h-4 animate-spin text-white" />
                <span>Compiling Dossier...</span>
              </>
            ) : (
              <>
                <FileCheck className="w-4 h-4 text-white" />
                <span>{reportText ? "Regenerate Report" : "Generate Report"}</span>
              </>
            )}
          </button>

          {reportText && (
            <button
              type="button"
              onClick={handleDownload}
              className="px-4 py-2 rounded-xl bg-emerald-600 hover:bg-emerald-500 text-white text-xs font-medium transition-colors shadow-xs flex items-center gap-2 cursor-pointer"
            >
              <Download className="w-4 h-4 text-white" />
              <span>Download .txt</span>
            </button>
          )}
        </div>
      </div>

      {/* Clean Report Preview */}
      <div className="bg-[#0b1220] rounded-2xl border border-slate-800 overflow-hidden shadow-sm">
        
        {/* Header Bar */}
        <div className="bg-slate-900 px-4 py-3 border-b border-slate-800 flex items-center justify-between text-xs text-slate-300">
          <div className="flex items-center gap-2">
            <FileText className="w-4 h-4 text-sky-400" />
            <span className="font-semibold text-white">Investigation Dossier Preview</span>
            <span className="text-slate-500 hidden sm:inline">| MARPOL Annex I Format</span>
          </div>

          {reportText && (
            <button 
              type="button"
              onClick={handleCopy}
              className="px-3 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs transition-colors flex items-center gap-1.5 cursor-pointer"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5 text-sky-400" />}
              <span>{copied ? "Copied to Clipboard" : "Copy Dossier"}</span>
            </button>
          )}
        </div>

        {/* Content Body */}
        <div className="p-5 sm:p-6 font-mono text-xs sm:text-sm text-slate-200 overflow-x-auto leading-relaxed max-h-[600px] overflow-y-auto selection:bg-sky-900 selection:text-white">
          {reportText ? (
            <pre className="whitespace-pre font-mono text-slate-200">
              {reportText}
            </pre>
          ) : (
            <div className="py-16 text-center text-slate-400 space-y-3">
              <FileText className="w-12 h-12 text-slate-600 mx-auto" />
              <p className="text-sm text-slate-300 max-w-md mx-auto">
                No report has been compiled yet. Click <span className="text-sky-400 font-semibold">"Generate Report"</span> above to synthesize live satellite and AIS telemetry.
              </p>
              <button
                type="button"
                onClick={generateReport}
                className="px-4 py-2 rounded-xl bg-slate-800 hover:bg-slate-700 text-sky-300 text-xs font-medium transition-colors border border-slate-700 cursor-pointer"
              >
                Compile Now
              </button>
            </div>
          )}
        </div>

      </div>

    </div>
  );
}
